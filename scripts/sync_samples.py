"""Keep frontend samples available without contacting the API."""

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))
from sample_transcripts import SAMPLES

text = "// Generated by scripts/sync_samples.py; edit backend/sample_transcripts.py instead.\n"
text += (
    "window.SENTINELCALL_SAMPLES = "
    + json.dumps([s.model_dump() for s in SAMPLES], ensure_ascii=False, indent=2)
    + ";\n"
)
path = ROOT / "frontend" / "samples.js"
parser = argparse.ArgumentParser()
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
if args.check:
    if not path.exists() or path.read_text() != text:
        sys.exit("Bundled samples are stale. Run python scripts/sync_samples.py.")
else:
    path.write_text(text)
